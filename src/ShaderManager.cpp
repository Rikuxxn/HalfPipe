//=============================================================================
// デバイスロスト時
//=============================================================================
void CShaderManager::OnLostDevice(void)
{
    for (auto& shader : m_Shaders)
    {
        shader.second->OnLostDevice();
    }
}

//=============================================================================
// デバイスリセット時
//=============================================================================
void CShaderManager::OnResetDevice(void)
{
    for (auto& shader : m_Shaders)
    {
        shader.second->OnResetDevice();
    }
}