//=============================================================================
// コンストラクタ
//=============================================================================
CBillboardRenderComponent::CBillboardRenderComponent() :
    m_pVtxBuff  (nullptr),
    m_Width     (100.0f),
    m_Height    (100.0f),
    m_Color     (ColorConst::DX::WHITE),
    m_isVisible (true)
{
    m_UV.left   = 0;
    m_UV.top    = 0;
    m_UV.right  = 1;
    m_UV.bottom = 1;
}

//=============================================================================
// 初期化処理
//=============================================================================
HRESULT CBillboardRenderComponent::Init(void)
{
    // デバイスの取得
    auto device = CManager::Instance()->GetRenderer()->GetDevice();

    if (FAILED(device->CreateVertexBuffer(
        sizeof(VERTEX_3D) * MathConst::VERTEX,
        D3DUSAGE_WRITEONLY,
        FVF_VERTEX_3D,
        D3DPOOL_MANAGED,
        m_pVtxBuff.GetAddressOf(),
        nullptr)))
    {
        return E_FAIL;
    }

    return S_OK;
}

//=============================================================================
// 描画処理
//=============================================================================
void CBillboardRenderComponent::Draw(void)
{
    if (!m_isVisible)
    {
        return;
    }

    auto transform = m_pOwner->GetComponent<CTransformComponent>();

    if (!transform)
    {
        return;
    }

    // デバイスの取得
    auto device = CManager::Instance()->GetRenderer()->GetDevice();

    VERTEX_3D* vertex = nullptr;

    // 頂点バッファをロックし、頂点情報へのポインタを取得
    m_pVtxBuff->Lock(0, 0, (void**)&vertex, 0);

    // 頂点の設定
    SetBillboardVertex(vertex);

    //頂点バッファをアンロックする
    m_pVtxBuff->Unlock();

    //-------------------------------------------------------------------------
    // 描画開始
    //-------------------------------------------------------------------------
    BeginBillboardDraw(device);

    //-------------------------------------------------------------------------
    // ビルボード行列
    //-------------------------------------------------------------------------
    SetBillboardTransform(device, transform->Position);

    //-------------------------------------------------------------------------
    // 描画
    //-------------------------------------------------------------------------
    DrawBillboard(device);

    //-------------------------------------------------------------------------
    // 描画終了
    //-------------------------------------------------------------------------
    EndBillboardDraw(device);
}

//=============================================================================
// ビルボード頂点設定
//=============================================================================
void CBillboardRenderComponent::SetBillboardVertex(VERTEX_3D* vertex, float /*rate*/)
{
    float halfW = m_Width * MathConst::HALF;
    float halfH = m_Height * MathConst::HALF;

    //-------------------------------------------------------------------------
    // 頂点座標
    //-------------------------------------------------------------------------
    vertex[0].pos = D3DXVECTOR3(-halfW, halfH, 0.0f);
    vertex[1].pos = D3DXVECTOR3(halfW, halfH, 0.0f);
    vertex[2].pos = D3DXVECTOR3(-halfW, -halfH, 0.0f);
    vertex[3].pos = D3DXVECTOR3(halfW, -halfH, 0.0f);

    //-------------------------------------------------------------------------
    // 法線・カラー
    //-------------------------------------------------------------------------
    for (int i = 0; i < MathConst::VERTEX; ++i)
    {
        // 法線の設定
        vertex[i].nor = D3DXVECTOR3(0.0f, 0.0f, -1.0f);

        // 色の設定
        vertex[i].col = m_Color;
    }

    //-------------------------------------------------------------------------
    // UV
    //-------------------------------------------------------------------------
    vertex[0].tex = D3DXVECTOR2(0.0f, 0.0f);
    vertex[1].tex = D3DXVECTOR2(1.0f, 0.0f);
    vertex[2].tex = D3DXVECTOR2(0.0f, 1.0f);
    vertex[3].tex = D3DXVECTOR2(1.0f, 1.0f);
}

//=============================================================================
// ビルボードワールド行列設定
//=============================================================================
void CBillboardRenderComponent::SetBillboardTransform(IDirect3DDevice9* device, const D3DXVECTOR3& position)
{
    D3DXMATRIX mtxView;
    D3DXMATRIX mtxTrans;

    //-------------------------------------------------------------------------
    // ワールド行列を初期化
    //-------------------------------------------------------------------------
    D3DXMatrixIdentity(&m_mtxWorld);

    //-------------------------------------------------------------------------
    // ビュー行列を取得
    //-------------------------------------------------------------------------
    device->GetTransform(D3DTS_VIEW, &mtxView);

    //-------------------------------------------------------------------------
    // カメラの回転を反映
    //-------------------------------------------------------------------------
    m_mtxWorld._11 = mtxView._11;
    m_mtxWorld._12 = mtxView._21;
    m_mtxWorld._13 = mtxView._31;

    m_mtxWorld._21 = mtxView._12;
    m_mtxWorld._22 = mtxView._22;
    m_mtxWorld._23 = mtxView._32;

    m_mtxWorld._31 = mtxView._13;
    m_mtxWorld._32 = mtxView._23;
    m_mtxWorld._33 = mtxView._33;

    //-------------------------------------------------------------------------
    // 位置
    //-------------------------------------------------------------------------
    D3DXMatrixTranslation(&mtxTrans, position.x, position.y, position.z);

    D3DXMatrixMultiply(&m_mtxWorld, &m_mtxWorld, &mtxTrans);

    //-------------------------------------------------------------------------
    // ワールド行列を設定
    //-------------------------------------------------------------------------
    device->SetTransform(D3DTS_WORLD, &m_mtxWorld);
}

//=============================================================================
// ビルボード描画開始
//=============================================================================
void CBillboardRenderComponent::BeginBillboardDraw(IDirect3DDevice9* device)
{
    //-------------------------------------------------------------------------
    // ライト無効
    //-------------------------------------------------------------------------
    device->SetRenderState(D3DRS_LIGHTING, FALSE);

    //-------------------------------------------------------------------------
    // Zテスト
    //-------------------------------------------------------------------------
    device->SetRenderState(D3DRS_ZFUNC, D3DCMP_LESSEQUAL);
    device->SetRenderState(D3DRS_ZWRITEENABLE, TRUE);

    //-------------------------------------------------------------------------
    // αテスト
    //-------------------------------------------------------------------------
    device->SetRenderState(D3DRS_ALPHATESTENABLE, TRUE);
    device->SetRenderState(D3DRS_ALPHAREF, 0);
    device->SetRenderState(D3DRS_ALPHAFUNC, D3DCMP_GREATER);
}

//=============================================================================
// ビルボード描画
//=============================================================================
void CBillboardRenderComponent::DrawBillboard(IDirect3DDevice9* device)
{
    //-------------------------------------------------------------------------
    // 頂点バッファ
    //-------------------------------------------------------------------------
    device->SetStreamSource(0, m_pVtxBuff.Get(), 0, sizeof(VERTEX_3D));

    //-------------------------------------------------------------------------
    // 頂点フォーマット
    //-------------------------------------------------------------------------
    device->SetFVF(FVF_VERTEX_3D);

    //-------------------------------------------------------------------------
    // テクスチャ
    //-------------------------------------------------------------------------
    device->SetTexture(0, m_TextureResource ? m_TextureResource->Texture.Get() : nullptr);

    //-------------------------------------------------------------------------
    // 描画
    //-------------------------------------------------------------------------
    device->DrawPrimitive(D3DPT_TRIANGLESTRIP, 0, 2);
}

//=============================================================================
// ビルボード描画終了
//=============================================================================
void CBillboardRenderComponent::EndBillboardDraw(IDirect3DDevice9* device)
{
    //-------------------------------------------------------------------------
    // αテスト無効
    //-------------------------------------------------------------------------
    device->SetRenderState(D3DRS_ALPHATESTENABLE, FALSE);

    //-------------------------------------------------------------------------
    // Z書き込みを元に戻す
    //-------------------------------------------------------------------------
    device->SetRenderState(D3DRS_ZWRITEENABLE, TRUE);

    //-------------------------------------------------------------------------
    // ライト有効
    //-------------------------------------------------------------------------
    device->SetRenderState(D3DRS_LIGHTING, TRUE);
}