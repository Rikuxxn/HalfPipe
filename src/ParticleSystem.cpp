CParticleSystem::CParticleSystem()
{

}

//=============================================================================
// デストラクタ
//=============================================================================
CParticleSystem::~CParticleSystem()
{

}

//=============================================================================
// エミッターの追加
//=============================================================================
void CParticleSystem::AddEmitter(CParticleEmitterComponent* emitter)
{
    if (!emitter)
    {
        return;
    }

    m_Emitters.push_back(emitter);
}

//=============================================================================
// エミッターの削除
//=============================================================================
void CParticleSystem::RemoveEmitter(CParticleEmitterComponent* emitter)
{
    m_Emitters.erase(
        std::remove(
            m_Emitters.begin(),
            m_Emitters.end(),
            emitter),
        m_Emitters.end());
}
