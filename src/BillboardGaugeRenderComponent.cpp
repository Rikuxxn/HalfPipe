//=============================================================================
// コンストラクタ
//=============================================================================
CBillboardGaugeRenderComponent::CBillboardGaugeRenderComponent() :
    m_Rate(1.0f)
{

}

//=============================================================================
// 描画処理
//=============================================================================
void CBillboardGaugeRenderComponent::Draw(void)
{
    // 非表示の場合は飛ばす
    if (!IsVisible())
    {
        return;
    }

    // トランスフォームコンポーネントの取得
    auto transform = m_pOwner->GetComponent<CTransformComponent>();

    if (!transform)
    {
        return;
    }

    // デバイスの取得
    auto device = CManager::Instance()->GetRenderer()->GetDevice();

    //-------------------------------------------------------------------------
    // 頂点設定
    //-------------------------------------------------------------------------
    VERTEX_3D* vertex = nullptr;

    if (FAILED(m_pVtxBuff->Lock(0, 0, reinterpret_cast<void**>(&vertex), 0)))
    {
        return;
    }

    SetBillboardVertex(vertex, GetRate());

    //-------------------------------------------------------------------------
    // アンロック
    //-------------------------------------------------------------------------
    m_pVtxBuff->Unlock();

    //-------------------------------------------------------------------------
    // 描画開始
    //-------------------------------------------------------------------------
    BeginBillboardDraw(device);

    //-------------------------------------------------------------------------
    // ビルボード行列
    //-------------------------------------------------------------------------
    SetBillboardTransform(device, transform->Position);

    //-------------------------------------------------------------------------
    // 描画
    //-------------------------------------------------------------------------
    DrawBillboard(device);

    //-------------------------------------------------------------------------
    // 描画終了
    //-------------------------------------------------------------------------
    EndBillboardDraw(device);
}

//=============================================================================
// 頂点設定
//=============================================================================
void CBillboardGaugeRenderComponent::SetBillboardVertex(VERTEX_3D* vertex, float /*rate*/)
{
    float halfW = m_Width * MathConst::HALF;
    float halfH = m_Height * MathConst::HALF;

    // 左端は固定
    float left = -halfW;

    // Rateに応じて右端を縮める
    float right = -halfW + (m_Width * m_Rate);

    //-------------------------------------------------------------------------
    // 頂点座標
    //-------------------------------------------------------------------------
    vertex[0].pos = D3DXVECTOR3(left, halfH, 0.0f);
    vertex[1].pos = D3DXVECTOR3(right, halfH, 0.0f);
    vertex[2].pos = D3DXVECTOR3(left, -halfH, 0.0f);
    vertex[3].pos = D3DXVECTOR3(right, -halfH, 0.0f);

    //-------------------------------------------------------------------------
    // 法線・カラー
    //-------------------------------------------------------------------------
    for (int i = 0; i < MathConst::VERTEX; ++i)
    {
        // 法線の設定
        vertex[i].nor = D3DXVECTOR3(0.0f, 0.0f, -1.0f);

        // 色の設定
        vertex[i].col = m_Color;
    }

    //-------------------------------------------------------------------------
    // UV
    //-------------------------------------------------------------------------
    vertex[0].tex = D3DXVECTOR2(0.0f, 0.0f);
    vertex[1].tex = D3DXVECTOR2(1.0f, 0.0f);
    vertex[2].tex = D3DXVECTOR2(0.0f, 1.0f);
    vertex[3].tex = D3DXVECTOR2(1.0f, 1.0f);
}

//=============================================================================
// レートの設定
//=============================================================================
void CBillboardGaugeRenderComponent::SetRate(float rate)
{
    m_Rate = MathUtil::Clamp(rate, 0.0f, 1.0f);
}

//=============================================================================
// レートの取得
//=============================================================================
float CBillboardGaugeRenderComponent::GetRate(void) const
{
    return m_Rate;
}