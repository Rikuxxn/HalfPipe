#include "SceneManager.h"
#include "Manager.h"
#include "CollisionSystem.h"


//=============================================================================
// コンストラクタ
//=============================================================================
CSceneManager::CSceneManager()
{
    m_Mode = CScene::Mode::Title;
}

//=============================================================================
// 初期化処理
//=============================================================================
HRESULT CSceneManager::Init(CScene::Mode mode)
{
    SetMode(mode);

    return S_OK;
}

//=============================================================================
// 更新処理
//=============================================================================
void CSceneManager::Update(void)
{
    if (m_CurrentScene)
    {
        m_CurrentScene->Update();
    }
}

//=============================================================================
// 描画処理
//=============================================================================
void CSceneManager::Draw(void)
{
    if (m_CurrentScene)
    {
        m_CurrentScene->Draw();
    }
}

//=============================================================================
// 描画処理(影用)
//=============================================================================
void CSceneManager::DrawShadow(void)
{
    if (m_CurrentScene)
    {
        m_CurrentScene->DrawShadow();
    }
}

//=============================================================================
// モードの設定
//=============================================================================
void CSceneManager::SetMode(CScene::Mode mode)
{
    //---------------------------------
    // 旧シーン破棄
    //---------------------------------

    if (m_CurrentScene)
    {
        // 衝突情報のクリア
        CManager::Instance()->GetCollisionSystem()->Clear();

        m_CurrentScene->Uninit();
    }

    m_CurrentScene.reset();

    //---------------------------------
    // 新シーン生成
    //---------------------------------

    m_CurrentScene = CScene::Create(mode);

    if (m_CurrentScene)
    {
        if (FAILED(m_CurrentScene->Init()))
        {
            m_CurrentScene.reset();
            return;
        }
    }

    //---------------------------------
    // モード保存
    //---------------------------------

    m_Mode = mode;
}