//=============================================================================
// コンストラクタ
//=============================================================================
CGhostObjectManager::CGhostObjectManager()
{

}

//=============================================================================
// デストラクタ
//=============================================================================
CGhostObjectManager::~CGhostObjectManager()
{

}

//=============================================================================
// 登録
//=============================================================================
void CGhostObjectManager::AddGhost(btGhostObject* ghost)
{
    if (!ghost)
    {
        return;
    }

    m_Ghosts.push_back(ghost);
}


//=============================================================================
// 削除
//=============================================================================
void CGhostObjectManager::RemoveGhost(btGhostObject* ghost)
{
    if (!ghost)
    {
        return;
    }

    auto itr = std::find(m_Ghosts.begin(), m_Ghosts.end(), ghost);

    if (itr != m_Ghosts.end())
    {
        m_Ghosts.erase(itr);
    }
}


//=============================================================================
// 取得
//=============================================================================
const std::vector<btGhostObject*>& CGhostObjectManager::GetGhosts(void) const
{
    return m_Ghosts;
}