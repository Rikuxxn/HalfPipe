#include "MathUtility.h"


//============================================================================= 
// 名前空間 MathUtil 
//============================================================================= 
namespace MathUtil 
{ 
	//========================================================================= 
	// 角度を度からラジアンへ変換 
	//========================================================================= 
	float ToRadians(float degree) 
	{ 
		return degree * (PI / 180.0f); 
	} 
	
	//=========================================================================
	// 角度をラジアンから度へ変換 
	//========================================================================= 
	float ToDegrees(float radian) 
	{ 
		return radian * (180.0f / PI);
	} 
	
	//=========================================================================
	// 最小値
	//=========================================================================
	float Min(float a, float b)
	{
		return (a < b) ? a : b;
	}
	float Min(int a, int b)
	{
		return (a < b) ? a : b;
	}

	//=========================================================================
	// 最大値
	//=========================================================================
	float Max(float a, float b)
	{
		return (a > b) ? a : b;
	}
	float Max(int a, int b)
	{
		return (a > b) ? a : b;
	}

	//=========================================================================
	// 値を範囲内にクランプ (float)
	//========================================================================= 
	float Clamp(float value, float min, float max)
	{ 
		if (value < min)
		{ 
			return min; 
		} 
		
		if (value > max)
		{ 
			return max; 
		} 
		
		return value;
	} 
	
	//=========================================================================
	// 値を範囲内にクランプ (int)
	//========================================================================= 
	float Clamp(int value, int min, int max)
	{
		if (value < min)
		{
			return min;
		}

		if (value > max)
		{
			return max;
		}

		return value;
	}

	//========================================================================= 
	// floatの線形補間 
	//=========================================================================
	float Lerp(float a, float b, float t) 
	{ 
		return a + (b - a) * t;
	} 
	
	//========================================================================= 
	// floatの最短方向の角度差
	//=========================================================================
	float LerpAngle(float current, float next, float t)
	{
		float diff = next - current;

		if (diff > PI)
		{
			diff -= PI * 2.0f;
		}
		else if (diff < -PI)
		{
			diff += PI * 2.0f;
		}

		return current + diff * t;
	}

	//========================================================================= 
	// D3DXVECTOR3の線形補間 
	//========================================================================= 
	D3DXVECTOR3 Lerp(const D3DXVECTOR3& a, const D3DXVECTOR3& b, float t)
	{ 
		return D3DXVECTOR3( Lerp(a.x, b.x, t), Lerp(a.y, b.y, t), Lerp(a.z, b.z, t) ); 
	} 
	
	//========================================================================= 
	// 2点間の距離 
	//========================================================================= 
	float Distance(const D3DXVECTOR3& a, const D3DXVECTOR3& b)
	{ 
		const float x = b.x - a.x; 
		const float y = b.y - a.y; 
		const float z = b.z - a.z; 
		
		return std::sqrt( x * x + y * y + z * z ); 
	} 
	
	//========================================================================= 
	// 2点間の距離の2乗 
	//========================================================================= 
	float DistanceSq(const D3DXVECTOR3& a, const D3DXVECTOR3& b) 
	{ 
		const float x = b.x - a.x;
		const float y = b.y - a.y; 
		const float z = b.z - a.z;
		
		return x * x + y * y + z * z; 
	} 
	
	//=========================================================================
	// ベクトルを正規化 
	//========================================================================= 
	D3DXVECTOR3 Normalize(const D3DXVECTOR3& v) 
	{ 
		D3DXVECTOR3 result = v; 
		
		// 長さが0の場合は正規化できない 
		if (D3DXVec3LengthSq(&result) <= 0.0000001f) 
		{ 
			return D3DXVECTOR3(0.0f, 0.0f, 0.0f); 
		} 
		
		D3DXVec3Normalize(&result, &result); 
		
		return result; 
	} 
	
	//=========================================================================
	// 角度を正規化 
	//========================================================================= 
	float Normalize(float angle)
	{
		while (angle > 180.0f)
		{
			angle -= 360.0f;
		}

		while (angle < -180.0f)
		{
			angle += 360.0f;
		}

		return angle;
	}

	//========================================================================= 
	// 内積
	//=========================================================================
	float Dot(const D3DXVECTOR3& a, const D3DXVECTOR3& b)
	{ 
		return a.x * b.x + a.y * b.y + a.z * b.z; 
	} 
	
	//=========================================================================
	// 外積 
	//========================================================================= 
	D3DXVECTOR3 Cross(const D3DXVECTOR3& a, const D3DXVECTOR3& b)
	{ 
		return D3DXVECTOR3( a.y * b.z - a.z * b.y, a.z * b.x - a.x * b.z, a.x * b.y - a.y * b.x );
	}
	
	//=========================================================================
	// 浮動小数点の誤差を考慮した比較 
	//========================================================================= 
	bool NearlyEqual(float a, float b, float epsilon) 
	{ 
		return std::fabs(a - b) <= epsilon; 
	} 

	//=========================================================================
	// スプライン
	//========================================================================= 
	D3DXVECTOR3 Spline(const D3DXVECTOR3& P0, const D3DXVECTOR3& P1, const D3DXVECTOR3& P2, const D3DXVECTOR3& P3, float t)
	{
		// 事前に計算
		float t2 = t * t;
		float t3 = t2 * t;

		D3DXVECTOR3 point;

		// キャットマルロムの計算式
		point.x = 0.5f * ((2.0f * P1.x) + (-P0.x + P2.x) * t + (2.0f * P0.x - 5.0f * P1.x + 4.0f * P2.x - P3.x) * t2 + (-P0.x + 3.0f * P1.x - 3.0f * P2.x + P3.x) * t3);
		point.y = 0.5f * ((2.0f * P1.y) + (-P0.y + P2.y) * t + (2.0f * P0.y - 5.0f * P1.y + 4.0f * P2.y - P3.y) * t2 + (-P0.y + 3.0f * P1.y - 3.0f * P2.y + P3.y) * t3);
		point.z = 0.5f * ((2.0f * P1.z) + (-P0.z + P2.z) * t + (2.0f * P0.z - 5.0f * P1.z + 4.0f * P2.z - P3.z) * t2 + (-P0.z + 3.0f * P1.z - 3.0f * P2.z + P3.z) * t3);

		return point;

	}
}