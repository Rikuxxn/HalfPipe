#include "GameTime.h"



//=============================================================================
// コンストラクタ
//=============================================================================
CGameTime::CGameTime() :
    m_Time      (0.0f),     // 経過時間
    m_DayLength (60.0f),   // 1日の長さ(秒) : ゲーム内1日を何秒にするか
    m_IsActive  (true)      // 動作中か
{

}

//=============================================================================
// デストラクタ
//=============================================================================
CGameTime::~CGameTime()
{

}

//=============================================================================
// 初期化
//=============================================================================
void CGameTime::Init(void)
{
    m_Time = 0.0f;
    m_IsActive = true;
}

//=============================================================================
// 更新
//=============================================================================
void CGameTime::Update(float dt)
{
    if (!m_IsActive)
    {
        return;
    }

    m_Time += dt;

    // 1日でループ
    if (m_Time >= m_DayLength)
    {
        m_Time -= m_DayLength;
    }
}

//=============================================================================
// 総時間
//=============================================================================
float CGameTime::GetTotalTime(void) const
{
    return m_Time;
}

//=============================================================================
// 時間割合
//=============================================================================
float CGameTime::GetTimeOfDay(void) const
{
    return m_Time / m_DayLength;
}

//=============================================================================
// 時
//=============================================================================
int CGameTime::GetHour(void) const
{
    float dayRate = GetTimeOfDay();

    // 24時間換算
    return (int)(dayRate * 24.0f);
}

//=============================================================================
// 分
//=============================================================================
int CGameTime::GetMinute(void) const
{
    float dayRate = GetTimeOfDay();

    float totalMinute = dayRate * 24.0f * 60.0f;

    return (int)totalMinute % 60;
}

//=============================================================================
// 秒
//=============================================================================
int CGameTime::GetSecond(void) const
{
    float dayRate = GetTimeOfDay();

    float totalSecond = dayRate * 24.0f * 60.0f * 60.0f;

    return (int)totalSecond % 60;
}

//=============================================================================
// 時計取得
//=============================================================================
void CGameTime::GetClock(int& hour, int& minute, int& second) const
{
    hour = GetHour();
    minute = GetMinute();
    second = GetSecond();
}

//=============================================================================
// リセット
//=============================================================================
void CGameTime::Reset(void)
{
    m_Time = 0.0f;
}

//=============================================================================
// 停止
//=============================================================================
void CGameTime::Stop(void)
{
    m_IsActive = false;
}

//=============================================================================
// 再開
//=============================================================================
void CGameTime::Start(void)
{
    m_IsActive = true;
}

//=============================================================================
// 動作中
//=============================================================================
bool CGameTime::IsActive(void) const
{
    return m_IsActive;
}