#ifndef _GAME_TIME_H_// このマクロ定義がされていなかったら
#define _GAME_TIME_H_// 2重インクルード防止のマクロ定義

//*****************************************************************************
// インクルードファイル
//*****************************************************************************


//*****************************************************************************
// ゲームタイムクラス
//*****************************************************************************
class CGameTime
{
public:
    CGameTime();
    ~CGameTime();

    // 初期化
    void Init(void);

    // 更新
    void Update(float dt);

    //---------------------------------
    // 経過時間
    //---------------------------------

    // 総秒数取得
    float GetTotalTime(void) const;

    //---------------------------------
    // ゲーム内時計
    //---------------------------------

    // 時
    int GetHour(void) const;

    // 分
    int GetMinute(void) const;

    // 秒
    int GetSecond(void) const;

    // 3:25:10形式取得
    void GetClock(int& hour, int& minute, int& second) const;

    //---------------------------------
    // 昼夜
    //---------------------------------

    // 0.0～1.0
    float GetTimeOfDay(void) const;

    //---------------------------------
    // 制御
    //---------------------------------

    // リセット
    void Reset(void);

    // 停止
    void Stop(void);

    // 再開
    void Start(void);

    // 動作中か
    bool IsActive(void) const;

private:

    // 経過時間
    float m_Time;

    // 1日の長さ(秒)
    // ゲーム内1日を何秒にするか
    float m_DayLength ;

    // 更新フラグ
    bool m_IsActive;
};

#endif