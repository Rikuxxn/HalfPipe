#ifndef _SOUND_MANAGER_H_// このマクロ定義がされていなかったら
#define _SOUND_MANAGER_H_// 2重インクルード防止のマクロ定義


//*****************************************************************************
// サウンドマネージャークラス
//*****************************************************************************
class CSoundManager
{
public:

    //=========================================================================
    // サウンドラベル
    //=========================================================================
    enum SOUND_LABEL
    {
        SOUND_LABEL_GAMEBGM = 0,
        SOUND_LABEL_TITLEBGM,
        SOUND_LABEL_FIRE,

        SOUND_LABEL_MAX,
    };


    //=========================================================================
    // サウンドの種類
    //=========================================================================
    enum class SoundCategory
    {
        BGM = 0,
        SE,
    };

    //=========================================================================
    // サウンドの空間タイプ
    //=========================================================================
    enum class SoundSpatial
    {
        SOUND_2D = 0,     // 画面上のどこで鳴っても同じ
        SOUND_3D,         // ワールド座標によって音量・定位が変化
    };

    //=========================================================================
    // サウンド再生ハンドル
    //=========================================================================
    using SoundHandle = int;

    static constexpr SoundHandle INVALID_HANDLE = -1;


public:

    CSoundManager();
    ~CSoundManager();

    //=========================================================================
    // 初期化・終了
    //=========================================================================

    HRESULT Init    (HWND hWnd);
    void    Uninit  (void);

    //=========================================================================
    // 更新
    //=========================================================================

    void Update(void);

    //=========================================================================
    // BGM
    //=========================================================================

    SoundHandle PlayBGM(SOUND_LABEL label);

    void StopBGM    (void);
    void PauseBGM   (void);
    void ResumeBGM  (void);

    //=========================================================================
    // 2Dサウンド
    //=========================================================================

    SoundHandle Play2D(SOUND_LABEL label);

    //=========================================================================
    // 3Dサウンド
    //=========================================================================

    SoundHandle Play3D(SOUND_LABEL label, const D3DXVECTOR3& position);

    //=========================================================================
    // サウンド停止
    //=========================================================================

    void Stop       (SoundHandle handle);
    void StopByLabel(SOUND_LABEL label);    // 指定したラベルをすべて停止
    void StopAll    (void);                 // すべて停止

    void PauseAll(void);
    void ResumeAll(void);

    //=========================================================================
    // 3Dサウンド更新
    //=========================================================================

    void UpdateListener     (const D3DXVECTOR3& position, const D3DXVECTOR3& front);
    void UpdateSoundPosition(SoundHandle handle, const D3DXVECTOR3& position);

    //=========================================================================
    // 音量
    //=========================================================================

    void SetMasterVolume(float volume);
    void SetBGMVolume   (float volume);
    void SetSEVolume    (float volume);

private:

    static constexpr int	INPUT_CHANNELS          = 1;		// モノラル音源
    static constexpr int	OUTPUT_CHANNELS         = 4;	    // FL, FR, RL, RR
    static constexpr float  MIN_BACK_VOLUME         = 0.6f;		// 後ろの聞こえる最低値
    static constexpr float  CURVE_DISTANCE_SCALER   = 150.0f;	// カーブ範囲

    //=========================================================================
    // サウンドデータ
    //=========================================================================
    struct SoundData
    {
        BYTE*                   pAudioData  = nullptr;
        DWORD                   audioBytes  = 0;
        WAVEFORMATEXTENSIBLE    wfx         = {};
    };

    //=========================================================================
    // サウンド情報
    //=========================================================================
    struct SoundInfo
    {
        std::string     filename        = "";
        SoundCategory   category        = SoundCategory::SE;
        SoundSpatial    spatial         = SoundSpatial::SOUND_2D;
        int             loopCount       = 0;
        int             maxInstances    = 0;
        float           volume          = 1.0f;
        float           minDistance     = 1.0f;
        float           maxDistance     = 100.0f;
    };

    //=========================================================================
    // 再生中サウンド
    //=========================================================================
    struct SoundInstance
    {
        SoundHandle             handle          = INVALID_HANDLE;
        SOUND_LABEL             label           = SOUND_LABEL_GAMEBGM;
        IXAudio2SourceVoice*    pSourceVoice    = nullptr;
        SoundSpatial            spatial         = SoundSpatial::SOUND_2D;
        X3DAUDIO_EMITTER        emitter         = {};
        D3DXVECTOR3             position        = INIT_VEC3;
        float                   minDistance     = 0.0f;
        float                   maxDistance     = 0.0f;
        float                   volume          = 1.0f;
        bool                    active          = false;
        bool                    looping         = false;
    };

private:

    //=========================================================================
    // 内部再生処理
    //=========================================================================

    SoundHandle PlayInternal(SOUND_LABEL label, const D3DXVECTOR3& position);

    //=========================================================================
    // SourceVoice生成・再生
    //=========================================================================

    HRESULT CreateAndStartVoice(SOUND_LABEL label, SoundInstance& instance);

    //=========================================================================
    // Wave読み込み
    //=========================================================================

    HRESULT LoadWave(SOUND_LABEL label);

    HRESULT CheckChunk(
        HANDLE hFile,
        DWORD format,
        DWORD* pChunkSize,
        DWORD* pChunkDataPosition
    );

    HRESULT ReadChunkData(
        HANDLE hFile,
        void* pBuffer,
        DWORD bufferSize,
        DWORD bufferOffset
    );

    //=========================================================================
    // サウンドリスト読み込み
    //=========================================================================

    HRESULT LoadSoundInfo(const char* pFilename);

    //=========================================================================
    // インスタンス検索
    //=========================================================================

    std::vector<SoundInstance>::iterator FindInstance(SoundHandle handle);

    //=========================================================================
    // 3Dサウンド更新
    //=========================================================================

    void Update3DSound(SoundInstance& instance);

    void CalculateCustomPanning(SoundInstance& instance, FLOAT32* matrix);

    //=========================================================================
    // 音量
    //=========================================================================

    void UpdateInstanceVolume(SoundInstance& instance, float attenuation);

    //=========================================================================
    // インスタンス管理
    //=========================================================================

    void DestroyInstance(SoundInstance& instance);

    int CountPlayingSounds(SOUND_LABEL label) const;

private:

    //=========================================================================
    // XAudio2
    //=========================================================================

    IXAudio2*               m_pXAudio2;
    IXAudio2MasteringVoice* m_pMasteringVoice;

    //=========================================================================
    // X3DAudio
    //=========================================================================

    X3DAUDIO_HANDLE     m_X3DInstance;
    X3DAUDIO_LISTENER   m_Listener;

    //=========================================================================
    // サウンドデータ
    //=========================================================================

    SoundData m_SoundData[SOUND_LABEL_MAX];

    //=========================================================================
    // サウンド情報
    //=========================================================================

    SoundInfo m_SoundInfo[SOUND_LABEL_MAX];

    //=========================================================================
    // 再生中インスタンス
    //=========================================================================

    std::vector<SoundInstance> m_Instances;

    //=========================================================================
    // ID発行
    //=========================================================================

    SoundHandle m_NextHandle;

    //=========================================================================
    // BGM
    //=========================================================================

    SoundHandle m_BGMHandle;

    //=========================================================================
    // リスナー
    //=========================================================================

    D3DXVECTOR3 m_ListenerPosition;

    //=========================================================================
    // 音量
    //=========================================================================

    float m_MasterVolume;
    float m_BGMVolume;
    float m_SEVolume;
};

#endif